#!/usr/bin/env node
/**
 * Refresh data/allowlist.json from the search engines' published IP ranges.
 *
 * middleware.ts raises the rate limit for verified crawlers, but only when the
 * request's IP is in one of these ranges — a Googlebot User-Agent header is
 * trivially forged, so it is never trusted on its own. lib/blocklist.ts also
 * refuses to block anything in this list, which stops a broad CIDR rule aimed
 * at abusive traffic from silently de-indexing the site.
 *
 * Run monthly (the ranges do drift), on the host, with network access:
 *
 *   node scripts/update-crawler-allowlist.mjs
 *
 * The app hot-reloads the file within 30s — no rebuild or restart.
 * If the file is missing, isAllowlisted() returns false everywhere and
 * crawlers simply get the normal rate limit. Failing this way round is
 * deliberate: a stale or absent allowlist must never open access up.
 */

import { writeFile, mkdir, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_PATH = join(ROOT, "data", "allowlist.json");

const SOURCES = [
  // Googlebot + the other common Google crawlers (this URL redirects to
  // common-crawlers.json, which is the same payload).
  {
    name: "googlebot",
    url: "https://developers.google.com/static/search/apis/ipranges/googlebot.json",
  },
  // Google-InspectionTool (URL Inspection in Search Console), Google-Extended, etc.
  {
    name: "google-special",
    url: "https://developers.google.com/static/crawling/ipranges/special-crawlers.json",
  },
  { name: "bingbot", url: "https://www.bing.com/toolbox/bingbot.json" },
];

async function fetchPrefixes({ name, url }) {
  const res = await fetch(url, {
    redirect: "follow",
    headers: { "User-Agent": "metascience-observatory-explorer/allowlist-updater" },
  });
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);

  const body = await res.json();
  const prefixes = body?.prefixes;
  if (!Array.isArray(prefixes) || prefixes.length === 0) {
    throw new Error(`${name}: no prefixes in response`);
  }

  const cidrs = prefixes
    .map((p) => p.ipv4Prefix ?? p.ipv6Prefix)
    .filter((c) => typeof c === "string" && c.includes("/"));
  if (cidrs.length === 0) throw new Error(`${name}: no usable CIDRs`);

  console.log(`  ${name.padEnd(16)} ${cidrs.length} ranges`);
  return cidrs;
}

async function main() {
  console.log("Fetching published crawler ranges...");

  const results = await Promise.allSettled(SOURCES.map(fetchPrefixes));

  const cidrs = new Set();
  const failed = [];
  results.forEach((result, i) => {
    if (result.status === "fulfilled") {
      result.value.forEach((c) => cidrs.add(c));
    } else {
      failed.push(`${SOURCES[i].name}: ${result.reason.message}`);
    }
  });

  // Never write a partial list: it would silently demote the missing crawler to
  // the normal rate limit, which is exactly the failure this file prevents.
  if (failed.length > 0) {
    console.error("\nFailed to fetch:");
    for (const f of failed) console.error(`  ${f}`);
    let existing = false;
    try {
      await readFile(OUT_PATH);
      existing = true;
    } catch {
      /* no existing file */
    }
    console.error(
      existing
        ? "\nKeeping the existing allowlist unchanged. Re-run when the network recovers."
        : "\nNo allowlist written. Crawlers will get the normal rate limit until this succeeds."
    );
    process.exit(1);
  }

  const sorted = [...cidrs].sort();
  const payload = {
    _comment:
      "Published search-engine crawler ranges. Generated by " +
      "scripts/update-crawler-allowlist.mjs - do not edit by hand. " +
      "Used to verify crawler User-Agents before raising their rate limit, and " +
      "to make them unblockable. Re-read automatically within 30s of a change.",
    _generated: new Date().toISOString(),
    _sources: SOURCES.map((s) => s.url),
    ips: [],
    cidrs: sorted,
  };

  await mkdir(dirname(OUT_PATH), { recursive: true });
  await writeFile(OUT_PATH, `${JSON.stringify(payload, null, 2)}\n`);

  const v4 = sorted.filter((c) => !c.includes(":")).length;
  console.log(`\nWrote ${sorted.length} ranges (${v4} IPv4, ${sorted.length - v4} IPv6)`);
  console.log(`  -> ${OUT_PATH}`);
}

main().catch((error) => {
  console.error("Failed:", error);
  process.exit(1);
});
